"""Prepare self-contained startup HTML; media stays separate and source files stay editable."""
from pathlib import Path
import re,html,hashlib,json
root=Path(__file__).resolve().parents[1]
entries=['modules/oreo/index.html','modules/timtam/index.html','modules/khapse/dist/embed.html','modules/kungu/index.html']
def public(path):return '/accept-all-cookies/'+path.relative_to(root).as_posix()
def css_text(path):
 s=path.read_text()
 def url(m):
  value=m.group(1).strip('"\' ')
  if value.startswith(('data:','http:','https:','/','#')):return m.group(0)
  return 'url('+json.dumps(public((path.parent/value).resolve()))+')'
 return re.sub(r'url\(([^)]+)\)',url,s)
for entry in entries:
 source=root/entry; text=source.read_text()
 def script(m):
  attrs,url=m.group(1),m.group(2)
  path=(root/url.removeprefix('/accept-all-cookies/') if url.startswith('/accept-all-cookies/') else source.parent/url).resolve()
  code=path.read_text()
  code=code.replace('document.currentScript.src','(document.currentScript.dataset.source?new URL(document.currentScript.dataset.source,location.href).href:document.currentScript.src)')
  if path.name=='timtam.js':
   style=css_text(path.with_name('timtam.css')).replace('`','\\`').replace('${','\\${')
   code=code.replace('<link rel="stylesheet" href="${base}timtam.css">','<style>'+style+'</style>')
  if path.name=='khapse.js':code=code.replace("else $('link').href = new URL('style.css', base).href;", "else {const style=document.createElement('style');style.textContent="+json.dumps(css_text(path.with_name('style.css')))+";$('link').replaceWith(style);}")
  return '<script data-source="'+html.escape(public(path),quote=True)+'">'+code.replace('</script','<\\/script')+'</script>'
 text=re.sub(r'<script\s+([^>]*?)src=["\']([^"\']+)["\'][^>]*>\s*</script>',script,text,flags=re.I)
 def sheet(m):
  path=(source.parent/m.group(1)).resolve();return '<style>'+css_text(path).replace('</style','<\\/style')+'</style>'
 text=re.sub(r'<link\s+rel=["\']stylesheet["\']\s+href=["\']([^"\']+)["\']\s*/?>',sheet,text,flags=re.I)
 target=source.with_name('host.html');target.write_text('<!-- Generated by tools/build-module-pages.py; edit original module sources. -->\n'+text)
 print(target.relative_to(root),len(text.encode()),'bytes')

manifest=root/'cookie-quest/integration/window-review.json'
records=json.loads(manifest.read_text())
for record in records:
 matches=[entry for entry in entries if entry.split('/')[1]==record['id']]
 if not matches:continue
 source=root/matches[0];target=source.with_name('host.html')
 relative=target.relative_to(root/'modules'/record['id']).as_posix()
 version=hashlib.sha256(target.read_bytes()).hexdigest()[:12]
 record['entry']=relative+'?v='+version+('&embed=1' if record['id']=='timtam' else '')
manifest.write_text(json.dumps(records,ensure_ascii=False,indent=2)+'\n')
