"""Embed the small essential SVG tools so one failed request cannot stop Kungu."""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1];app=root/'modules/kungu/app.js';s=app.read_text()
assets={'assets/'+p.name:'data:image/svg+xml;charset=utf-8,'+__import__('urllib.parse',fromlist=['quote']).quote(p.read_text()) for p in (root/'modules/kungu/assets').glob('*.svg')}
line='const bundledArt='+json.dumps(assets,ensure_ascii=False,separators=(',',':'))+';'
if 'const bundledArt=' in s:s=re.sub(r'^const bundledArt=.*;$',lambda m:line,s,flags=re.M)
else:s=s.replace("'use strict';","'use strict';\n// Generated by tools/build-kungu-assets.py.\n"+line,1)
app.write_text(s)
